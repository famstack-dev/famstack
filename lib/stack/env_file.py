"""A stacklet's `.env`: the file `stack up` renders its settings into.

`stack up <id>` writes it next to the stacklet's manifest, and docker
compose hands it to the stacklet's containers (`env_file`). A command
whose work runs in the bot runner reads it back, so that work sees the
settings the stacklet's containers see (`stack.bot_runner.call_stacklet`).
Both directions live here, so the format has one definition:

    KEY="value"

one line per key, sorted, every value in double quotes with `\\` and `"`
escaped, after a header comment. The file is derived (ADR-006): `stack up`
overwrites it, and nothing else writes it.
"""

from __future__ import annotations

import re
from pathlib import Path

HEADER = "# Auto-generated by stack — do not edit"

_LINE = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*)="((?:[^"\\]|\\.)*)"$')
_ESCAPED = re.compile(r"\\(.)")


def render(env: dict) -> str:
    """The file's text for `env`. Values are quoted and escaped, so a
    password with `"` or `\\` in it survives."""
    lines = [HEADER, ""]
    for key, value in sorted(env.items()):
        escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'{key}="{escaped}"')
    return "\n".join(lines) + "\n"


def read(path: Path) -> dict[str, str]:
    """The settings in the file at `path`, as `render` wrote them. Lines
    in any other shape (the header, a blank line) are not settings."""
    env = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if match := _LINE.match(line):
            env[match.group(1)] = _ESCAPED.sub(r"\1", match.group(2))
    return env
